"""Snapshot installed Omarchy palettes; Python 3.11+, no build-time OS dependency.

Uses the same named-role / terminal-color mapping as WaveSink. Reads colors only;
never executes theme code or copies backgrounds, fonts, or terminal configuration.
"""
import argparse
import json
from pathlib import Path
import re
import tomllib

REQUIRED = {'accent', 'background', 'foreground', 'bright_foreground', 'red', 'yellow', 'green'}
ROLES = 'accent selection muted background dark_background darker_background lighter_background foreground dark_foreground light_foreground bright_foreground red yellow orange green cyan blue magenta brown bright_red bright_yellow bright_green bright_cyan bright_blue bright_magenta'.split()
HEX = re.compile(r'#[0-9a-fA-F]{6}\Z')
LABELS = {'retropc': 'RetroPC', 'synthwave84': "Synthwave '84", 'blackgold': 'Black Gold'}


def luminance(color):
    values = [int(color[i:i+2], 16) / 255 for i in (1, 3, 5)]
    return sum((v/12.92 if v <= .04045 else ((v+.055)/1.055)**2.4)*w for v, w in zip(values, (.2126, .7152, .0722)))


def mix(color, factor):
    return '#' + ''.join(f'{max(0,min(255,round(int(color[i:i+2],16)*factor))):02x}' for i in (1, 3, 5))


def terminal(data):
    if 'colors' in data:
        c = data['colors']
        primary, normal, bright = (c.get(k, {}) for k in ('primary', 'normal', 'bright'))
        bg, fg = primary['background'], primary['foreground']
        accent = c.get('cursor', {}).get('cursor') or c.get('cursor', {}).get('background') or normal.get('blue') or normal.get('cyan') or bright.get('blue') or fg
        selection = c.get('selection', {}).get('background')
        muted = normal.get('black') if luminance(bg) <= .5 else bright.get('black')
    else:
        bg, fg = data['background'], data['foreground']
        normal = dict(zip(('black','red','green','yellow','blue','magenta','cyan','white'), (data.get(f'color{i}') for i in range(8))))
        bright = dict(zip(normal, (data.get(f'color{i}') for i in range(8, 16))))
        accent = data.get('accent') or data.get('cursor') or normal['blue']
        selection, muted = data.get('selection_background'), bright.get('black')
    dark = luminance(bg) <= .5
    return {
        'accent': accent, 'background': bg, 'foreground': fg,
        'selection': selection or mix(bg, 1.8 if dark else .92),
        'muted': muted or mix(bg, 2.4 if dark else .8),
        'dark_background': mix(bg, .75 if dark else .96),
        'darker_background': mix(bg, .55 if dark else .92),
        'lighter_background': mix(bg, 1.7 if dark else .97),
        'dark_foreground': bright.get('black') or mix(fg, .65),
        'light_foreground': mix(fg, 1.08),
        'bright_foreground': bright.get('white') or mix(fg, 1.15),
        **{k: normal.get(k) for k in ('red','yellow','green','cyan','blue','magenta')},
        **{f'bright_{k}': bright.get(k) for k in ('red','yellow','green','cyan','blue','magenta')},
    }


def palette(path):
    source = path / 'colors.toml'
    raw = tomllib.loads(source.read_text()) if source.exists() else {}
    colors = {k: v for k, v in raw.items() if k in ROLES and isinstance(v, str) and HEX.fullmatch(v)}
    if not REQUIRED <= colors.keys():
        fallback = terminal(raw) if 'color1' in raw else terminal(tomllib.loads((path/'alacritty.toml').read_text()))
        colors = {**fallback, **colors}
    colors = {k: colors[k] for k in ROLES if isinstance(colors.get(k), str) and HEX.fullmatch(colors[k])}
    if not REQUIRED <= colors.keys():
        raise ValueError(f'{path.name}: incomplete palette')
    mode = raw.get('mode') or ('light' if luminance(colors['background']) > .5 else 'dark')
    if mode not in ('light', 'dark'):
        raise ValueError(f'{path.name}: invalid mode')
    return {'id': path.name, 'label': LABELS.get(path.name, path.name.replace('-', ' ').title()), 'mode': mode, 'colors': colors}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stock', type=Path, default=Path('/usr/share/omarchy/themes'))
    parser.add_argument('--custom', type=Path, default=Path.home()/'.config/omarchy/themes')
    args = parser.parse_args()
    themes = {}
    counts = {}
    for origin, root in [('stock', args.stock), ('custom', args.custom)]:
        paths = sorted(p for p in root.iterdir() if p.is_dir())
        counts[origin] = len(paths)
        for path in paths:
            themes[path.name] = {**palette(path), 'origin': origin}
    output = Path(__file__).resolve().parents[1]/'src/themes/omarchy.ts'
    output.write_text('// Generated by scripts/import-themes.py from installed color palettes.\n'
                      '// Runtime never needs these source directories.\n'
                      'export const BUNDLED_THEMES = '+json.dumps(sorted(themes.values(), key=lambda t: t['id']), indent=2)+' as const;\n'
                      'export type BundledTheme = (typeof BUNDLED_THEMES)[number];\n')
    print(f"Bundled {len(themes)} themes: {counts['stock']} stock, {counts['custom']} custom.")


if __name__ == '__main__':
    main()
